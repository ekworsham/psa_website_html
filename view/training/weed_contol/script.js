const state = {
  current: 0,
  passed: Array(topics.length).fill(false),
  scores: Array(topics.length).fill(null),
  completed: false
};

const $ = id => document.getElementById(id);
const STORAGE_KEY = "proscapesWeedTraining";

function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));

    if (!saved) return;

    state.current = Math.min(
      saved.current ?? 0,
      topics.length - 1
    );

    if (Array.isArray(saved.passed) && saved.passed.length === topics.length) {
      state.passed = saved.passed;
    }

    if (Array.isArray(saved.scores) && saved.scores.length === topics.length) {
      state.scores = saved.scores;
    }

    state.completed = !!saved.completed;
  } catch (error) {
    console.warn("Unable to load saved training progress.", error);
  }
}

function saveState() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

function renderNav() {
  $("topicNav").innerHTML = topics.map((topic, index) => {
    const unlocked = index === 0 || state.passed[index - 1];
    const complete = state.passed[index];

    return `
      <button
        class="topic-btn ${index === state.current ? "active" : ""}
        ${complete ? "complete" : ""}
        ${!unlocked ? "locked" : ""}"
        data-i="${index}"
        ${!unlocked ? "disabled" : ""}
      >
        <span class="topic-num">${complete ? "✓" : index + 1}</span>
        <span>${topic.title}</span>
      </button>
    `;
  }).join("");

  document.querySelectorAll(".topic-btn").forEach(button => {
    button.addEventListener("click", () => {
      goTo(Number(button.dataset.i));
    });
  });
}

function updateProgress() {
  const completedCount = state.passed.filter(Boolean).length;
  const percent = Math.round((completedCount / topics.length) * 100);

  $("progressPercent").textContent = `${percent}%`;
  $("progressBar").style.width = `${percent}%`;
  $("mobileTopic").textContent =
    `Topic ${state.current + 1} of ${topics.length}`;
}

function renderTopic() {
  const topic = topics[state.current];
  const hasQuiz = Array.isArray(topic.questions) && topic.questions.length > 0;

  $("topicKicker").textContent = topic.kicker;
  $("topicTitle").textContent = topic.title;
  $("contentArea").innerHTML = topic.content;

  // Show quiz only when this topic has questions.
  $("quizArea").classList.toggle("hidden", !hasQuiz);

  // Show final acknowledgement only on the final topic.
  $("ackArea").classList.toggle("hidden", !topic.final);

  // Reset acknowledgement when entering the final stage.
  $("ackCheckbox").checked = false;
  $("completeBtn").disabled = true;

  if (hasQuiz) {
    renderQuiz(topic);
  } else {
    $("quizQuestions").innerHTML = "";
    $("quizFeedback").className = "quiz-feedback hidden";
    $("quizScoreBadge").textContent = "";
  }

  $("prevBtn").disabled = state.current === 0;

  if (topic.final) {
    $("nextBtn").classList.add("hidden");
  } else {
    $("nextBtn").classList.remove("hidden");
    $("nextBtn").textContent = "Next →";
    $("nextBtn").disabled = !state.passed[state.current];
  }

  updateProgress();
  renderNav();

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}

function renderQuiz(topic) {
  $("quizTitle").textContent = "Check Your Understanding";

  const bestScore = state.scores[state.current];

  $("quizScoreBadge").textContent =
    bestScore !== null
      ? `Best score: ${bestScore}%`
      : "";

  $("quizQuestions").innerHTML = topic.questions.map((question, index) => `
    <div class="question">
      <h3>${index + 1}. ${question.q}</h3>

      ${question.options.map((option, optionIndex) => `
        <label class="option">
          <input
            type="radio"
            name="q${index}"
            value="${optionIndex}"
          >
          <span>${option}</span>
        </label>
      `).join("")}
    </div>
  `).join("");

  $("quizFeedback").className = "quiz-feedback hidden";

  $("submitQuizBtn").textContent =
    state.passed[state.current]
      ? "Passed — Retake Check"
      : "Submit Knowledge Check";
}

function submitQuiz() {
  const topic = topics[state.current];

  if (!topic.questions?.length) return;

  let correct = 0;
  let answered = 0;

  topic.questions.forEach((question, index) => {
    const selected = document.querySelector(
      `input[name="q${index}"]:checked`
    );

    if (!selected) return;

    answered++;

    if (Number(selected.value) === question.answer) {
      correct++;
    }
  });

  if (answered < topic.questions.length) {
    $("quizFeedback").className = "quiz-feedback fail";
    $("quizFeedback").textContent =
      `Please answer all ${topic.questions.length} questions before submitting.`;
    return;
  }

  const score = Math.round(
    (correct / topic.questions.length) * 100
  );

  const previousBest = state.scores[state.current] ?? 0;

  state.scores[state.current] = Math.max(
    score,
    previousBest
  );

  const passed = score === 100;

  if (passed) {
    state.passed[state.current] = true;
  }

  saveState();
  updateProgress();
  renderNav();

  $("quizFeedback").className =
    `quiz-feedback ${passed ? "pass" : "fail"}`;

  $("quizFeedback").textContent = passed
    ? `Passed — ${score}%. You may continue to the next topic.`
    : `Score: ${score}%. You need 100% to continue. Review this section and try again.`;

  $("submitQuizBtn").textContent =
    passed
      ? "Retake Knowledge Check"
      : "Try Again";

  $("quizScoreBadge").textContent =
    `Best score: ${state.scores[state.current]}%`;

  $("nextBtn").disabled =
    !state.passed[state.current];
}

function goTo(index) {
  if (index < 0 || index >= topics.length) return;

  // Employees must pass the previous stage before moving forward.
  if (index > 0 && !state.passed[index - 1]) return;

  state.current = index;
  saveState();
  renderTopic();
}

$("startBtn").addEventListener("click", () => {
  $("welcomeScreen").classList.add("hidden");
  $("trainingScreen").classList.remove("hidden");
  renderTopic();
});

$("submitQuizBtn").addEventListener("click", submitQuiz);

$("prevBtn").addEventListener("click", () => {
  goTo(state.current - 1);
});

$("nextBtn").addEventListener("click", () => {
  goTo(state.current + 1);
});

$("ackCheckbox").addEventListener("change", event => {
  $("completeBtn").disabled = !event.target.checked;
});

$("completeBtn").addEventListener("click", () => {
  if (state.current !== topics.length - 1) return;

  state.passed[state.current] = true;
  state.completed = true;

  saveState();
  updateProgress();

  $("trainingScreen").classList.add("hidden");
  $("completionScreen").classList.remove("hidden");
});

$("restartBtn").addEventListener("click", () => {
  $("completionScreen").classList.add("hidden");
  $("trainingScreen").classList.remove("hidden");

  state.current = topics.length - 1;

  renderTopic();
});

loadState();

if (state.completed) {
  $("welcomeScreen").classList.add("hidden");
  $("trainingScreen").classList.add("hidden");
  $("completionScreen").classList.remove("hidden");
} else {
  renderNav();
  updateProgress();
}